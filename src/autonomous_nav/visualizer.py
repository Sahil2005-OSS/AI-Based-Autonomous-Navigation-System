"""
Interactive 2D Pygame Visualizer for Autonomous Navigation System.

Visualizes:
- The discrete occupancy grid and obstacles.
- Start and goal positions.
- The computed A* trajectory.
- The collision-safe smoothed route (when enabled), visually distinguished from the original A* path.
- The active robot position marker with interactive step-through and playback (discrete mode).
- Continuous robot pose, rotated heading indicator, and lookahead point (continuous-motion mode).
- A live telemetry status panel and legend.

Keyboard Controls (Discrete Waypoint Mode):
- SPACE: Advance robot marker by one waypoint.
- P or A: Toggle automatic playback.
- R: Reset robot marker to start.
- ESC or Q: Close visualizer.

Keyboard Controls (Continuous Motion Mode):
- SPACE or P: Pause / resume continuous motion.
- R: Reset robot pose and controller to initial start.
- ESC or Q: Close visualizer.
"""

from __future__ import annotations

import math
import sys
from typing import List, Optional, Tuple
import numpy as np

import pygame

from autonomous_nav.world import World, CELL_OCCUPIED, CELL_FREE, CELL_CLEARANCE_VIOLATION
from autonomous_nav.planner import PathResult
from autonomous_nav.motion_model import RobotState, KinematicMotionModel
from autonomous_nav.controller import (
    PurePursuitController,
    ControllerStatus,
    ControllerOutput,
    step_simulation,
)


# -----------------------------------------------------------------------------
# Color Palette (High contrast, modern dark theme)
# -----------------------------------------------------------------------------
COLOR_BG = (15, 17, 23)                 # Main background
