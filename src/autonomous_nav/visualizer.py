COLOR_PANEL_BORDER = (40, 45, 62)       # Sidebar separator line
COLOR_GRID_FREE = (28, 32, 46)          # Free cell fill
COLOR_GRID_LINE = (36, 42, 60)          # Grid wireframe lines
COLOR_OBSTACLE = (220, 53, 69)          # Obstacle cell fill (crimson)
COLOR_OBSTACLE_BORDER = (160, 30, 45)   # Obstacle outline
COLOR_CLEARANCE_ZONE = (45, 38, 58)     # Robot footprint clearance inflation zone
COLOR_FOOTPRINT_RING = (56, 189, 248)   # Circular robot footprint boundary (cyan)
COLOR_PATH = (0, 212, 255)              # Single path mode (cyan)
COLOR_PATH_NODE = (0, 150, 200)         # Single path waypoint nodes
COLOR_PATH_ORIGINAL = (70, 120, 170)    # Original A* route (muted steel blue)
COLOR_PATH_SMOOTHED = (255, 215, 0)     # Smoothed route (vibrant gold/amber)
COLOR_START = (40, 167, 69)             # Start marker (emerald green)
COLOR_GOAL = (255, 193, 7)              # Goal marker (amber/gold)
COLOR_ROBOT = (255, 99, 71)             # Active robot marker (coral red)
COLOR_ROBOT_RING = (255, 255, 255)      # Robot highlight ring (white)
COLOR_LOOKAHEAD = (0, 255, 220)         # Lookahead target indicator (turquoise)
COLOR_TEXT_PRIMARY = (240, 242, 245)    # Primary text
COLOR_TEXT_MUTED = (140, 148, 165)      # Secondary muted text
COLOR_TEXT_ACCENT = (0, 212, 255)       # Highlight text (cyan)
COLOR_SUCCESS = (40, 167, 69)           # Success indicator (green)
COLOR_DANGER = (220, 53, 69)            # Failure indicator (red)
COLOR_WARNING = (255, 165, 0)           # Warning indicator (amber/orange)
COLOR_DYNAMIC_OBSTACLE = (236, 72, 153) # Dynamic obstacle body (vibrant pink)
COLOR_DYNAMIC_PATROL = (120, 50, 90)    # Dynamic patrol guide segment
COLOR_DYNAMIC_BUFFER = (180, 80, 140)   # Dynamic obstacle clearance margin ring


class SimulationVisualizer:
    """
    Renders the occupancy grid, obstacles, start/goal markers, and A* path
    in a Pygame window with step-by-step interactive controls or continuous
    kinematic motion tracking.
    """

    def __init__(
        self,
        world: World,
        path_result: PathResult,
        start_grid: Tuple[int, int],
        goal_grid: Tuple[int, int],
        connectivity: int = 8,
        smoothed_path: Optional[List[Tuple[int, int]]] = None,
        cell_size: Optional[int] = None,
        sidebar_width: int = 260,
        fps: int = 30,
        init_display: bool = True,
        continuous_motion: bool = False,
        max_linear_speed: float = 40.0,
        max_angular_speed: float = 2.5,
        lookahead_distance: float = 25.0,
        goal_tolerance: float = 5.0,
        check_footprint: bool = False,
        robot_radius: Optional[float] = None,
        dynamic_obstacles: Optional[List[Any]] = None,
    ) -> None:
        """
        Initialize the visualizer.

        Args:
            world: An initialized `World` instance.
            path_result: `PathResult` generated by `AStarPlanner`.
            start_grid: Start cell coordinate (gx, gy).
            goal_grid: Goal cell coordinate (gx, gy).
            connectivity: 4 or 8 connected mode.
            smoothed_path: Optional smoothed route from `PathSmoother`.
            cell_size: Pixel size per grid cell (auto-calculated if None).
            sidebar_width: Width of the right telemetry panel in pixels.
            fps: Target rendering frames per second.
            init_display: If True, initializes Pygame display surface.
                          Can be False for headless testing.
            continuous_motion: If True, runs continuous kinematic motion tracking.
            max_linear_speed: Maximum linear velocity for motion controller.
            max_angular_speed: Maximum angular velocity for motion controller.
            lookahead_distance: Pure Pursuit lookahead distance.
            goal_tolerance: Pure Pursuit arrival tolerance distance.
            check_footprint: If True, renders clearance inflation zone and robot footprint circle.
            robot_radius: Optional override for robot radius. Defaults to world.robot_radius.
            dynamic_obstacles: Optional list of DynamicObstacle instances.
        """
        self.world = world
        self.path_result = path_result
        self.start_grid = start_grid
        self.goal_grid = goal_grid
        self.connectivity = connectivity
        self.smoothed_path = list(smoothed_path) if smoothed_path else None
        self.sidebar_width = sidebar_width
        self.fps = fps
        self.continuous_motion = continuous_motion
        self.check_footprint = bool(check_footprint)
        self.robot_radius = float(robot_radius if robot_radius is not None else world.robot_radius)
        if dynamic_obstacles is not None:
            self.dynamic_obstacles = list(dynamic_obstacles)
        else:
            self.dynamic_obstacles = list(getattr(world, "dynamic_obstacles", []))
        self.replans_count = 0

        # Compute scaling cell size to fit desktop screens comfortably
        if cell_size is None:
            max_arena_w = 960
            max_arena_h = 720
            self.cell_size = max(
                4,
                min(max_arena_w // self.world.grid_width, max_arena_h // self.world.grid_height)
            )
        else:
            self.cell_size = max(2, cell_size)

        self.arena_width = self.world.grid_width * self.cell_size
        self.arena_height = self.world.grid_height * self.cell_size
        self.window_width = self.arena_width + self.sidebar_width
        self.window_height = max(self.arena_height, 600)

        # Discrete simulation state
        self.path = list(path_result.path) if path_result.success else []
        self.current_step_index = 0
        self.auto_play = False
        self.auto_play_delay_ms = 80  # Step advance interval in auto-play
        self.last_step_time_ms = 0
        self.running = False

        # Continuous motion simulation state
        self.motion_model = KinematicMotionModel(
            max_linear_speed=max_linear_speed,
            max_angular_speed=max_angular_speed,
        )
        self.controller = PurePursuitController(
            world=self.world,
            lookahead_distance=lookahead_distance,
            max_linear_speed=max_linear_speed,
            max_angular_speed=max_angular_speed,
            goal_tolerance=goal_tolerance,
            check_footprint=self.check_footprint,
            robot_radius=self.robot_radius,
        )

        tracking_path = self.smoothed_path if self.smoothed_path else self.path
        start_wx, start_wy = self.world.grid_to_world(*self.start_grid)
        if tracking_path and len(tracking_path) > 1:
            p0 = self.world.grid_to_world(*tracking_path[0])
            p1 = self.world.grid_to_world(*tracking_path[1])
            init_theta = math.atan2(p1[1] - p0[1], p1[0] - p0[0])
        else:
            init_theta = 0.0

        self.initial_robot_state = RobotState(x=start_wx, y=start_wy, theta=init_theta)
        self.robot_state = RobotState(x=start_wx, y=start_wy, theta=init_theta)
        self.controller_output: Optional[ControllerOutput] = None
        self.motion_paused = False
        self.motion_elapsed_time = 0.0

        if tracking_path:
            self.controller.set_path(tracking_path)

        # Pygame handles
        self.screen: Optional[pygame.Surface] = None
        self.clock: Optional[pygame.time.Clock] = None
        self.font_title: Optional[pygame.font.Font] = None
        self.font_bold: Optional[pygame.font.Font] = None
        self.font_regular: Optional[pygame.font.Font] = None
        self.font_mono: Optional[pygame.font.Font] = None

        if init_display:
            self.setup_display()

    def setup_display(self) -> None:
        """Initialize Pygame display subsystem, fonts, and window surface."""
        if not pygame.get_init():
            pygame.init()
        if not pygame.font.get_init():
            pygame.font.init()

        pygame.display.set_caption("AI Autonomous Navigation - Simulation")
        self.screen = pygame.display.set_mode((self.window_width, self.window_height))
        self.clock = pygame.time.Clock()

        # Load clean system fonts with fallbacks
        self.font_title = pygame.font.SysFont("Segoe UI, Helvetica, Arial", 18, bold=True)
        self.font_bold = pygame.font.SysFont("Segoe UI, Helvetica, Arial", 14, bold=True)
        self.font_regular = pygame.font.SysFont("Segoe UI, Helvetica, Arial", 13)
        self.font_mono = pygame.font.SysFont("Consolas, Courier New, monospace", 12)

    # -------------------------------------------------------------------------
    # State Inspection & Step Controls
    # -------------------------------------------------------------------------

    @property
    def current_position(self) -> Tuple[int, int]:
        """Return the current robot grid position (gx, gy)."""
        if self.continuous_motion:
            try:
                return self.world.world_to_grid(self.robot_state.x, self.robot_state.y)
            except ValueError:
                return self.start_grid
        if self.path and 0 <= self.current_step_index < len(self.path):
            return self.path[self.current_step_index]
        return self.start_grid

    @property
    def is_at_goal(self) -> bool:
        """Check whether the robot marker has reached the goal."""
        if self.continuous_motion:
            return self.controller.status == ControllerStatus.REACHED_GOAL
        if not self.path:
            return False
        return self.current_step_index >= len(self.path) - 1

    def step_forward(self) -> bool:
        """
        Advance the robot marker by one waypoint (discrete mode).

        Returns:
            True if advanced, False if already at final waypoint or no path.
        """
        if not self.path or self.is_at_goal:
            return False
        self.current_step_index += 1
        return True

    def step_motion(self, dt: float) -> None:
        """
        Advance one continuous motion simulation step (continuous mode), updating
        dynamic obstacles, detecting route conflicts, and triggering safe replanning.

        Args:
            dt: Frame time delta in seconds.
        """
        if not self.continuous_motion or self.motion_paused:
            return
        if self.controller.status in (ControllerStatus.REACHED_GOAL, ControllerStatus.COLLISION, ControllerStatus.BLOCKED):
            return

        sim_time = self.motion_elapsed_time

        # Synchronize dynamic obstacles with simulation time
        for dyn in self.dynamic_obstacles:
            dyn.current_time = sim_time

        # Dynamic obstacle route conflict check and safe replanning
        if self.dynamic_obstacles and len(self.controller.world_path) > 0:
            from autonomous_nav.dynamic_obstacle import (
                check_route_conflict,
                create_temporary_planning_world,
                find_safe_start_grid,
            )
            from autonomous_nav.planner import AStarPlanner
            from autonomous_nav.path_smoother import PathSmoother

            remaining_pts = [(self.robot_state.x, self.robot_state.y)] + self.controller.world_path[self.controller.current_segment_index:]
            is_conflict, conf_dyn, _ = check_route_conflict(
                remaining_pts,
                self.dynamic_obstacles,
                robot_radius=self.robot_radius,
                safety_margin=5.0,
                current_time=sim_time,
            )

            if is_conflict:
                temp_world = create_temporary_planning_world(
                    self.world,
                    self.dynamic_obstacles,
                    safety_margin=5.0,
                    current_time=sim_time,
                )
                start_cell = find_safe_start_grid(self.world, temp_world, self.robot_state.x, self.robot_state.y)
                goal_cell = self.controller.grid_path[-1]

                if start_cell is not None:
                    planner = AStarPlanner(
                        temp_world,
                        connectivity=self.connectivity,
                        strict_diagonal_clearance=True,
                        use_footprint=True,
                    )
                    plan_res = planner.plan(start_cell, goal_cell)

                    if plan_res.success and plan_res.path:
                        smoother = PathSmoother(temp_world, check_footprint=True)
                        smooth_res = smoother.smooth_result(plan_res)
                        new_path = smooth_res.smoothed_path if smooth_res.success else plan_res.path

                        path_safe = (
                            all(
                                temp_world.is_swept_footprint_safe(
                                    *temp_world.grid_to_world(*p1),
                                    *temp_world.grid_to_world(*p2),
                                )
                                for p1, p2 in zip(new_path[:-1], new_path[1:])
                            )
                            if len(new_path) >= 2
                            else True
                        )

                        if path_safe:
                            self.smoothed_path = new_path
                            self.controller.set_path(new_path)
                            self.replans_count += 1
                        else:
                            self.robot_state = RobotState(x=self.robot_state.x, y=self.robot_state.y, theta=self.robot_state.theta, v=0.0, omega=0.0)
                            self.controller.status = ControllerStatus.BLOCKED
                            return
                    else:
                        self.robot_state = RobotState(x=self.robot_state.x, y=self.robot_state.y, theta=self.robot_state.theta, v=0.0, omega=0.0)
                        self.controller.status = ControllerStatus.BLOCKED
                        return
                else:
                    self.robot_state = RobotState(x=self.robot_state.x, y=self.robot_state.y, theta=self.robot_state.theta, v=0.0, omega=0.0)
                    self.controller.status = ControllerStatus.BLOCKED
                    return

        self.robot_state, self.controller_output = step_simulation(
            self.robot_state,
            self.controller,
            self.motion_model,
            dt,
            dynamic_obstacles=self.dynamic_obstacles,
            current_time=sim_time,
        )
        self.motion_elapsed_time += dt

        # Advance dynamic obstacle clocks to match updated elapsed time
        for dyn in self.dynamic_obstacles:
            dyn.current_time = self.motion_elapsed_time

    def reset(self) -> None:
        """Reset the robot marker to the start position and reset dynamic obstacles."""
        for dyn in self.dynamic_obstacles:
            dyn.reset()
        self.replans_count = 0

        if self.continuous_motion:
            self.robot_state = RobotState(
                x=self.initial_robot_state.x,
                y=self.initial_robot_state.y,
                theta=self.initial_robot_state.theta,
                v=0.0,
                omega=0.0,
            )
            tracking_path = self.smoothed_path if self.smoothed_path else self.path
            self.controller.set_path(tracking_path)
            self.controller_output = None
            self.motion_paused = False
            self.motion_elapsed_time = 0.0
        else:
            self.current_step_index = 0
            self.auto_play = False

    def toggle_autoplay(self) -> None:
        """Toggle automatic playback mode in discrete stepping mode."""
        if self.continuous_motion:
            self.toggle_motion_pause()
            return
        if not self.path:
            self.auto_play = False
            return
        if self.is_at_goal:
            self.current_step_index = 0
        self.auto_play = not self.auto_play

    def toggle_motion_pause(self) -> None:
        """Toggle pause/resume in continuous motion mode."""
        self.motion_paused = not self.motion_paused

    # -------------------------------------------------------------------------
    # Coordinate Conversion & Rendering Methods
    # -------------------------------------------------------------------------

    def grid_to_screen_center(self, gx: int, gy: int) -> Tuple[int, int]:
        """Convert grid coordinate (gx, gy) to center pixel coordinate on screen."""
        px = int(gx * self.cell_size + self.cell_size / 2)
        py = int(gy * self.cell_size + self.cell_size / 2)
        return (px, py)

    def world_to_screen(self, wx: float, wy: float) -> Tuple[int, int]:
        """Convert continuous world coordinate (wx, wy) to screen pixel coordinate."""
        scale = self.cell_size / self.world.grid_resolution
        return (int(wx * scale), int(wy * scale))

    def draw_arena(self, surface: pygame.Surface) -> None:
        """Render the occupancy grid, wireframe, clearance inflation zone, and obstacles."""
        arena_rect = pygame.Rect(0, 0, self.arena_width, self.arena_height)
        pygame.draw.rect(surface, COLOR_GRID_FREE, arena_rect)
        cs = self.cell_size

        # 1. Draw clearance inflation zone if footprint check is active
        if self.check_footprint and hasattr(self.world, "clearance_grid"):
            clearance_indices = np.argwhere(self.world.clearance_grid == CELL_CLEARANCE_VIOLATION)
            for gy, gx in clearance_indices:
                rx = int(gx * cs)
                ry = int(gy * cs)
                pygame.draw.rect(surface, COLOR_CLEARANCE_ZONE, (rx, ry, cs, cs))

        # 2. Draw occupied obstacle cells
        occupied_indices = np.argwhere(self.world.grid == CELL_OCCUPIED)
        for gy, gx in occupied_indices:
            rx = int(gx * cs)
            ry = int(gy * cs)
            pygame.draw.rect(surface, COLOR_OBSTACLE, (rx, ry, cs, cs))

        # 3. Draw subtle grid lines if cells are large enough
        if cs >= 8:
            for x in range(0, self.arena_width + 1, cs):
                pygame.draw.line(surface, COLOR_GRID_LINE, (x, 0), (x, self.arena_height), 1)
            for y in range(0, self.arena_height + 1, cs):
                pygame.draw.line(surface, COLOR_GRID_LINE, (0, y), (self.arena_width, y), 1)

    def draw_path(self, surface: pygame.Surface) -> None:
        """Render the computed trajectories (original A* and smoothed route)."""
        if self.smoothed_path and len(self.smoothed_path) >= 2:
            # 1a. Render original A* path as muted underlying guide
            if self.path and len(self.path) >= 2:
                orig_points = [self.grid_to_screen_center(gx, gy) for gx, gy in self.path]
                pygame.draw.lines(surface, COLOR_PATH_ORIGINAL, False, orig_points, 2)
                for pt in orig_points:
                    pygame.draw.circle(surface, COLOR_PATH_ORIGINAL, pt, max(1, int(self.cell_size * 0.1)))

            # 1b. Render smoothed shortcut route in vibrant gold
            smooth_points = [self.grid_to_screen_center(gx, gy) for gx, gy in self.smoothed_path]
            smooth_width = max(2, int(self.cell_size * 0.28))
            pygame.draw.lines(surface, COLOR_PATH_SMOOTHED, False, smooth_points, smooth_width)
            for pt in smooth_points:
                pygame.draw.circle(surface, COLOR_PATH_SMOOTHED, pt, max(2, int(self.cell_size * 0.2)))
                pygame.draw.circle(surface, (255, 255, 255), pt, max(1, int(self.cell_size * 0.1)))

        elif self.path and len(self.path) >= 2:
            # Standard single path display
            pixel_points = [self.grid_to_screen_center(gx, gy) for gx, gy in self.path]
            line_width = max(2, int(self.cell_size * 0.25))
            pygame.draw.lines(surface, COLOR_PATH, False, pixel_points, line_width)
            for pt in pixel_points:
                pygame.draw.circle(surface, COLOR_PATH_NODE, pt, max(2, int(self.cell_size * 0.15)))

    def draw_markers(self, surface: pygame.Surface) -> None:
        """Render Start, Goal, active Robot markers, physical footprint circle, and directional indicator."""
        cs = self.cell_size
        scale = cs / self.world.grid_resolution
        phys_footprint_px = max(4, int(self.robot_radius * scale))

        # 1. Start Marker
        sx, sy = self.grid_to_screen_center(*self.start_grid)
        start_radius = max(3, int(cs * 0.45))
        pygame.draw.circle(surface, COLOR_START, (sx, sy), start_radius)
        pygame.draw.circle(surface, (255, 255, 255), (sx, sy), max(2, int(start_radius * 0.4)))

        # 2. Goal Marker
        gx, gy = self.grid_to_screen_center(*self.goal_grid)
        goal_radius = max(3, int(cs * 0.45))
        pygame.draw.circle(surface, COLOR_GOAL, (gx, gy), goal_radius)
        pygame.draw.circle(surface, (255, 255, 255), (gx, gy), max(2, int(goal_radius * 0.4)))

        # 3. Robot Marker
        if self.continuous_motion:
            # Draw lookahead target indicator
            if self.controller_output and self.controller_output.lookahead_target:
                tx, ty = self.world_to_screen(*self.controller_output.lookahead_target)
                pygame.draw.circle(surface, COLOR_LOOKAHEAD, (tx, ty), max(3, int(cs * 0.3)), 2)

            # Continuous robot position
            rx, ry = self.world_to_screen(self.robot_state.x, self.robot_state.y)
            robot_radius = max(4, int(cs * 0.48))

            # Physical footprint boundary ring
            if self.robot_radius > 0.0:
                pygame.draw.circle(surface, COLOR_FOOTPRINT_RING, (rx, ry), phys_footprint_px, 1)

            pygame.draw.circle(surface, COLOR_ROBOT, (rx, ry), robot_radius)
            pygame.draw.circle(surface, COLOR_ROBOT_RING, (rx, ry), robot_radius, max(1, int(cs * 0.15)))

            # Directional heading indicator (rotated arrow / triangle)
            L = robot_radius + 7
            tip_x = int(rx + L * math.cos(self.robot_state.theta))
            tip_y = int(ry + L * math.sin(self.robot_state.theta))
            wing_l_x = int(rx + 0.5 * L * math.cos(self.robot_state.theta + 2.5))
            wing_l_y = int(ry + 0.5 * L * math.sin(self.robot_state.theta + 2.5))
            wing_r_x = int(rx + 0.5 * L * math.cos(self.robot_state.theta - 2.5))
            wing_r_y = int(ry + 0.5 * L * math.sin(self.robot_state.theta - 2.5))
            pygame.draw.polygon(
                surface, (255, 255, 255), [(tip_x, tip_y), (wing_l_x, wing_l_y), (wing_r_x, wing_r_y)]
            )
        else:
            # Discrete waypoint position
            rx, ry = self.grid_to_screen_center(*self.current_position)
            robot_radius = max(4, int(cs * 0.48))

            # Physical footprint boundary ring
            if self.robot_radius > 0.0:
                pygame.draw.circle(surface, COLOR_FOOTPRINT_RING, (rx, ry), phys_footprint_px, 1)

            pygame.draw.circle(surface, COLOR_ROBOT, (rx, ry), robot_radius)
            pygame.draw.circle(surface, COLOR_ROBOT_RING, (rx, ry), robot_radius, max(1, int(cs * 0.15)))

    def draw_sidebar(self, surface: pygame.Surface) -> None:
        """Render the right telemetry status panel, metrics, and keyboard legend."""
        panel_rect = pygame.Rect(self.arena_width, 0, self.sidebar_width, self.window_height)
        pygame.draw.rect(surface, COLOR_PANEL_BG, panel_rect)
        pygame.draw.line(
            surface, COLOR_PANEL_BORDER,
            (self.arena_width, 0), (self.arena_width, self.window_height), 2
        )

        if not self.font_title or not self.font_regular or not self.font_bold or not self.font_mono:
            return

        pad_x = self.arena_width + 16
        y = 20

        # Title
        title_surf = self.font_title.render("AUTONOMOUS NAV", True, COLOR_TEXT_PRIMARY)
        surface.blit(title_surf, (pad_x, y))
        y += 24
        sub_text = "Kinematic Motion & Controller" if self.continuous_motion else "A* Simulator & Smoother"
        sub_surf = self.font_regular.render(sub_text, True, COLOR_TEXT_MUTED)
        surface.blit(sub_surf, (pad_x, y))
        y += 28

        # Section: Planning Status
        pygame.draw.line(surface, COLOR_PANEL_BORDER, (pad_x, y), (self.window_width - 16, y), 1)
        y += 12

        status_text = "FOUND" if self.path_result.success else "FAILED"
        status_color = COLOR_SUCCESS if self.path_result.success else COLOR_DANGER
        self._draw_label_value(surface, pad_x, y, "Plan Status:", status_text, status_color)
        y += 22

        conn_text = f"{self.connectivity}-Connected"
        self._draw_label_value(surface, pad_x, y, "Topology:", conn_text, COLOR_TEXT_PRIMARY)
        y += 22

