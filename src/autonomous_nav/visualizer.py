    def _draw_label_value(
        self,
        surface: pygame.Surface,
        x: int,
        y: int,
        label: str,
        value: str,
        value_color: Tuple[int, int, int]
    ) -> None:
        """Helper to render aligned label-value pair in sidebar."""
        assert self.font_regular is not None and self.font_bold is not None
        lbl_surf = self.font_regular.render(label, True, COLOR_TEXT_MUTED)
        val_surf = self.font_bold.render(value, True, value_color)
        surface.blit(lbl_surf, (x, y))
        surface.blit(val_surf, (x + 115, y))

    def _draw_legend_item(
        self,
        surface: pygame.Surface,
        x: int,
        y: int,
        color: Tuple[int, int, int],
        label: str
    ) -> None:
        """Helper to render a colored circle legend entry."""
        assert self.font_regular is not None
        pygame.draw.circle(surface, color, (x + 6, y + 6), 5)
        lbl_surf = self.font_regular.render(label, True, COLOR_TEXT_PRIMARY)
        surface.blit(lbl_surf, (x + 18, y))

    def draw_dynamic_obstacles(self, surface: pygame.Surface) -> None:
        """Render active dynamic obstacles, their bounded patrol lines, and safety margin rings."""
        if not self.dynamic_obstacles:
            return

        scale = self.cell_size / self.world.grid_resolution

        for dyn in self.dynamic_obstacles:
            # 1. Bounded patrol segment
            p1 = self.world_to_screen(*dyn.start_position)
            p2 = self.world_to_screen(*dyn.end_position)
            pygame.draw.line(surface, COLOR_DYNAMIC_PATROL, p1, p2, 2)
            pygame.draw.circle(surface, COLOR_DYNAMIC_PATROL, p1, 3)
            pygame.draw.circle(surface, COLOR_DYNAMIC_PATROL, p2, 3)

            # 2. Moving obstacle body and clearance buffer ring
            pos = dyn.current_position if hasattr(dyn, "current_position") else dyn.start_position
            cx, cy = self.world_to_screen(*pos)
            radius_px = max(3, int(dyn.radius * scale))
            buffer_px = max(radius_px + 2, int((dyn.radius + 5.0) * scale))

            # Safety margin outline
            pygame.draw.circle(surface, COLOR_DYNAMIC_BUFFER, (cx, cy), buffer_px, 1)

            # Solid dynamic obstacle core
            pygame.draw.circle(surface, COLOR_DYNAMIC_OBSTACLE, (cx, cy), radius_px)
            pygame.draw.circle(surface, (255, 255, 255), (cx, cy), max(2, int(radius_px * 0.35)))

    def render_frame(self) -> None:
        """Render a single complete frame to the active screen."""
        if self.screen is None:
            return

        self.screen.fill(COLOR_BG)
        self.draw_arena(self.screen)
        self.draw_path(self.screen)
        self.draw_dynamic_obstacles(self.screen)
        self.draw_markers(self.screen)
        self.draw_sidebar(self.screen)
        pygame.display.flip()

    # -------------------------------------------------------------------------
    # Main Interactive Loop
    # -------------------------------------------------------------------------

    def run(self) -> None:
        """Start the interactive simulation loop."""
        if self.screen is None:
            self.setup_display()

        assert self.clock is not None
        self.running = True

        while self.running:
            raw_dt = self.clock.tick(self.fps) / 1000.0
            bounded_dt = min(0.1, max(0.001, raw_dt))
            current_time = pygame.time.get_ticks()

            # 1. Event Handling
            for event in pygame.event.get():
                if event.type == pygame.QUIT:
                    self.running = False

                elif event.type == pygame.KEYDOWN:
                    if event.key in (pygame.K_ESCAPE, pygame.K_q):
                        self.running = False
                    elif self.continuous_motion:
                        if event.key in (pygame.K_SPACE, pygame.K_p, pygame.K_a):
                            self.toggle_motion_pause()
                        elif event.key == pygame.K_r:
                            self.reset()
                    else:
                        if event.key == pygame.K_SPACE:
                            self.auto_play = False
                            self.step_forward()
                        elif event.key in (pygame.K_p, pygame.K_a):
                            self.toggle_autoplay()
                        elif event.key == pygame.K_r:
                            self.reset()

            # 2. Progression
            if self.continuous_motion:
                self.step_motion(bounded_dt)
            elif self.auto_play and self.path:
                if current_time - self.last_step_time_ms >= self.auto_play_delay_ms:
                    if not self.step_forward():
                        self.auto_play = False
                    self.last_step_time_ms = current_time

            # 3. Draw Frame
            self.render_frame()

        self.cleanup()

    def cleanup(self) -> None:
        """Cleanly close Pygame display."""
        if pygame.get_init():
            pygame.quit()
        self.screen = None
        self.running = False
